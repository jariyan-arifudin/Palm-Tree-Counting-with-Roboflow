"""## Catatan & tips

- **CONF_THRESHOLD**: naikkan kalau banyak deteksi palsu (*false positive*), turunkan kalau banyak pohon yang terlewat.
- **DEDUP_DIST_M**: sesuaikan dengan jarak tanam sawit riil di lapangan supaya dua pohon yang memang berdekatan tidak keliru dianggap 1 pohon.
- Bounding box dihitung dari `width`/`height` prediksi Roboflow di tiap tile, lalu 4 sudutnya dikonversi ke koordinat peta lewat transform tile masing-masing — jadi ukurannya ikut skala asli raster, bukan ukuran tile 640px.
- Kalau raster kamu masih **geografis (WGS84)**, sebaiknya reproject dulu ke UTM (lewat QGIS, `gdalwarp`, atau `rasterio.warp`) sebelum diproses — hasil hitung jarak & luas jadi lebih akurat. Notebook ini tetap jalan untuk raster geografis (pakai pendekatan konversi derajat->meter), tapi UTM lebih presisi.
- Soal ECW: tidak dipakai karena proprietary (butuh SDK berbayar Hexagon/Erdas, tidak ada di GDAL open-source). Kalau suatu saat butuh format raster ringan buat arsip/serving raster resolusi penuh (bukan cuma preview peta), alternatif open-source yang setara tujuannya adalah **Cloud Optimized GeoTIFF (COG)** — bisa dibuat lewat `gdal_translate -of COG input.tif output_cog.tif`.
- Peta interaktif memakai preview yang di-downsample (maksimal 2000px sisi terpanjang) supaya ringan di browser; cukup untuk overview, bukan untuk analisis piksel presisi.
- Kalau request ke Roboflow gagal terus (timeout dsb): cek dulu kuota API di dashboard Roboflow, atau kemungkinan jaringan kampus/kantor memblokir domain `detect.roboflow.com`.
- API key Roboflow di Langkah 1 tertanam langsung di notebook — kalau notebook ini mau dibagikan ke orang lain/publik, sebaiknya pindahkan ke **Colab Secrets** (ikon kunci di sidebar kiri), lalu panggil dengan:\n`from google.colab import userdata`\n`ROBOFLOW_API_KEY = userdata.get('ROBOFLOW_API_KEY')`

"""